import { SHEET } from '../lib/names.js';
import {
  hasSecondaryMajors,
  primaryMajor,
  secondaryMajors,
  type GenerateConfig,
} from '../lib/majors.js';
import {
  defineSheet,
  text,
  title,
  type SheetSpec,
} from '../lib/template/index.js';

/** Manual (매뉴얼): usage instructions, tailored to the generated config. */
export function manualSheet(config: GenerateConfig): SheetSpec {
  const primary = primaryMajor(config);
  const secondaries = secondaryMajors(config);
  const multi = hasSecondaryMajors(config);

  const majorSheetList = config.majors
    .map((m) => `${m.sheetName}(${m.role})`)
    .join(', ');

  const lines: string[] = [
    '',
    '이 파일은 전남대학교 졸업요건 점검용 플래너입니다. 매크로/스크립트 없이',
    '셀 수식만으로 동작하므로 Google Sheets, LibreOffice, Excel에서 모두 사용할 수 있습니다.',
    '',
    '[중요] 이 파일의 모든 설정(전공/역할, 졸업 기준학점, 입학연도, 계열)은 홈페이지에서 파일을 생성할 때 이미 확정되어 읽기 전용으로 들어 있습니다.',
    '(졸업 최소 평점과 교양최대인정학점은 사용자가 고르는 값이 아니라 주전공 학과 기준으로 자동 결정됩니다.)',
    '값을 바꾸려면 홈페이지에서 옵션을 다시 선택해 파일을 새로 생성하세요.',
    '이 파일에서 직접 입력하는 곳은 대시보드의 "이수 과목 입력" 표(및 "학년·학기별 이수 현황")뿐입니다.',
    '',
    '[시트 구성]',
    `· 대시보드: 이수 과목을 입력하고, 이수구분별 학점·총 이수학점·GPA·졸업요건 충족 여부를 봅니다. (입력 표만 편집 가능)`,
    `· 전공 시트(${majorSheetList}): 각 전공의 졸업소요학점(읽기 전용)과 교육과정 목록입니다.`,
    '· 교양: 교양 교과목 목록입니다(읽기 전용). 대시보드는 이 목록을 참조하여 자동완성합니다.',
    '· 참조: 등급→평점표, 졸업 최소 평점(GPA), 교양최대인정학점, 중복인정 상한(모두 읽기 전용).',
    '· 마이크로디그리: 교과목 목록(읽기 전용 참고 자료).',
    '',
    '[입력 방법]',
    '· 모든 입력은 "대시보드" 시트의 "이수 과목 입력" 표에서만 합니다. (노란색 칸이 입력, 회색 칸은 자동 계산.)',
    '1. "학년"을 드롭다운으로 선택합니다 (1학년~6학년; 전 학년 개설 과목은 "전체").',
    '2. "학기"를 드롭다운으로 선택합니다 (1학기/여름학기/여름특별학기/2학기/겨울학기/겨울특별학기).',
    '   (계절·특별학기 학점도 모두 학점·GPA에 포함됩니다 — 학칙 제22조·제51조.)',
    '3. "코드"를 입력하면 "교과목명"·"학점"·"이수구분"이 자동으로 채워집니다.',
    `   (전공 시트들을 선언 순서대로 먼저 찾고(주전공 우선: ${primary.sheetName}), 없으면 교양에서 찾습니다. 같은 코드는 앞선 전공이 우선합니다.)`,
    '   (어느 목록에도 없는 코드는 값이 비어 있고 이수구분은 "일선"으로 처리됩니다.)',
    '4. "등급"을 드롭다운으로 선택합니다 (A+, A0, …, F, P, NP). "평점"은 자동 계산(P/NP는 GPA 제외).',
    '· [재수강] 같은 코드를 여러 번 입력하면 가장 아래 행만 집계에 반영되고 이전 행은 자동 제외됩니다.',
    '  ※ 교학규정 제55조: 재수강은 기 이수 C+ 이하만 가능, 성적 최대 A0, 원취득 무효. 이 플래너는 강제하지 않으니 사용자가 규정에 맞게 입력하세요.',
    '· 행이 부족하면 마지막 행을 아래로 드래그해 늘릴 수 있습니다.',
    '',
    '[대시보드 보는 법]',
    '· 상단 요약표(이수구분별·총 이수학점·GPA)의 이수학점/필요학점과 충족여부(✅/❌)를 보여줍니다.',
    '· "일반선택" 이수학점에는 교양·전공 초과 학점이 자동 합산됩니다 (아래 참고).',
    '· 요약표·교양 영역 의무이수·다중전공 요건이 각각 충족(✅)인지 항목별로 확인하세요.',
    '· "교양 영역 의무이수 현황"(교육과정 편성 및 운영 지침 제10조②③): 창의·감성·공동체 각 3, 기초SW 3, 표현과소통 3, 진로와창업 2, 인문학교양 8학점.',
    `  계열별 요건(제10조④)은 이 파일의 계열(${config.student.track})에 해당하는 항목만 표에 표시됩니다: 이공계열은 인간과사회 3 + 기초과학 3, 인문사회/예체능계열은 자연과기술 3학점.`,
    '· 입력표 오른쪽 "학년·학기별 이수 현황"에 학년·학기를 입력하면 그 학기의 이수학점·평균평점이 계산됩니다.',
    '',
    '[전공 구성 — 교육과정편성 제14·16~20조]',
    `· 이 파일의 전공 구성: ${multi ? config.majors.map((m) => m.role).join(' + ') : '단일전공'} (생성 시 확정).`,
  ];

  if (multi) {
    lines.push(
      '· 다중전공(복수/부/연계전공)을 선택했으므로 "전공심화" 21학점 요건은 해제(기준 0)되었습니다.',
      '· 각 전공의 과목은 코드가 그 전공 시트 목록에 있으면 자동으로 그 전공에 귀속되어 "다중전공 이수 현황"에 집계됩니다.',
      '  같은 코드가 여러 전공에 있으면 앞선 전공(주전공 우선)에 귀속됩니다.',
      '· 복수/연계전공은 대상 전공의 전공인정학점(전필+전선; 전공심화는 단일전공 전용 요건이라 제외), 부전공은 21학점 이상(교육과정편성 제17조②)을 충족해야 졸업 가능으로 표시됩니다.',
      '  (각 전공 시트 오른쪽의 "…최소 이수학점"이 전필+전선으로 자동 계산되어 표시됩니다.)',
      '· [중복인정 상한] 주전공과 복수/부전공에 공통 편성된 과목은 주전공 학점으로 인정하면서, 그 전공 학점으로도 상한까지 중복 인정됩니다.',
      '  상한은 복수·연계전공 9학점(복수전공규정 제10조 / 지침 제9조③), 부전공 6학점(지침 제9조② / 제17조③)입니다. "참조" 시트의 "중복인정 상한(학점)"에 표시됩니다.',
      '  → 공통과목이 상한을 넘으면 초과분은 그 전공 학점으로 인정되지 않으므로, 나머지는 공통이 아닌(예: 전공선택) 과목으로 채워야 합니다 (지침 제9조①).',
    );
    for (const m of secondaries) {
      lines.push(`  - ${m.sheetName}: ${m.role}`);
    }
  } else {
    lines.push(
      '· 단일전공이므로 "전공심화" 21학점 요건이 적용됩니다 (교육과정편성 제14조②③).',
      '· 복수/부/연계전공을 반영하려면 홈페이지에서 해당 전공을 추가해 파일을 새로 생성하세요.',
    );
  }

  lines.push(
    '',
    '[교양·전공 초과학점 처리 — 교육과정편성 제10조·제14조]',
    '· 교양 취득학점이 주전공 교양 기준(교양필수+교양선택)을 넘으면, 초과분은 교양최대인정학점 범위 내에서 일반선택으로 인정됩니다.',
    '· 교양최대인정학점을 넘는 교양 학점은 졸업소요학점으로 인정되지 않습니다(총 이수학점에서 제외).',
    '· 주전공 전공 취득학점이 기준을 넘으면 초과분은 제한 없이 일반선택으로 인정됩니다.',
    '',
    '[계열 판정 안내]',
    '· 계열(이공/인문사회/예체능)은 임의 선택값이 아니라 소속 학과/학부가 속한 대학(단과대학) 구분에 따릅니다 (교학규정 별표1).',
    '· 정확한 계열은 학과 사무실 / 학사요람 / 교학규정 별표1에서 확인하세요. (홈페이지 생성 시 선택합니다.)',
    '',
    '[주의]',
    '· 셀 수식만 사용하므로 파일을 열면 자동으로 다시 계산됩니다.',
    '· 졸업요건은 학과/입학연도에 따라 다르니 반드시 공식 규정을 확인하세요.',
    '· 마이크로디그리는 졸업요건이 아니며, 해당 과목은 본래 이수구분으로 계산됩니다.',
  );

  return defineSheet({
    name: SHEET.manual,
    columns: [{ index: 1, width: 100 }],
    regions: [title('사용 안내', { height: 24 }), text(lines, { leading: 1 })],
    protect: {},
  });
}
